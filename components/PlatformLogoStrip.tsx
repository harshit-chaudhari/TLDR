export default function PlatformLogoStrip({ selected, onChange }: PlatformLogoStripProps) {
  const handleToggle = (platform: Platform) => {
    if (selected.includes(platform)) {
      // If deselecting and it's the last one, select all
      if (selected.length === 1) {
        onChange([...allPlatforms]);
      } else {
        onChange(selected.filter(p => p !== platform));
      }
    } else {
      onChange([...selected, platform]);
    }
  };

  const isSelected = (platform: Platform) => {
    return selected.length === 0 || selected.length === allPlatforms.length || selected.includes(platform);
  };

  return (
    <div className="w-full py-8 border-y border-tldr-lightGray/20 bg-tldr-dark/50 backdrop-blur-sm">
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="flex flex-wrap items-center justify-center gap-6 sm:gap-8 md:gap-12">
          {allPlatforms.map((platform) => {
            const Logo = PlatformLogos[platform];
            const selected = isSelected(platform);

            return (
              <button
                key={platform}
                onClick={() => handleToggle(platform)}
                className={`group relative transition-all duration-300 ${
                  selected
                    ? 'opacity-100 scale-100'
                    : 'opacity-30 scale-95 hover:opacity-50'
                }`}
                aria-label={platform}
              >
                <div className={`transition-colors duration-300 ${
                  selected ? 'text-white' : 'text-gray-600'
                }`}>
                  <Logo />
                </div>

                {/* Active indicator */}
                {selected && (
                  <div className="absolute -bottom-2 left-0 right-0 h-0.5 bg-tldr-gold rounded-full" />
                )}

                {/* Hover tooltip */}
                <div className="absolute -bottom-8 left-1/2 transform -translate-x-1/2 opacity-0 group-hover:opacity-100 transition-opacity duration-200 pointer-events-none">
                  <span className="text-xs text-gray-400 whitespace-nowrap">
                    {selected ? 'Deselect' : 'Select'} {platform}
                  </span>
                </div>
              </button>
            );
          })}
        </div>

        {/* Selection indicator */}
        <div className="text-center mt-6">
          <p className="text-xs text-gray-500">
            {selected.length === 0 || selected.length === allPlatforms.length
              ? 'Showing all platforms'
              : `Showing ${selected.length} platform${selected.length > 1 ? 's' : ''}`}
          </p>
        </div>
      </div>
    </div>
  );
}
